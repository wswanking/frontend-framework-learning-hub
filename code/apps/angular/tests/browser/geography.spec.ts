test('IOT-GEO-001 filters, drills to device, and keeps unlocated devices accessible', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/geography');
  await expect(page.getByRole('heading', { name: '全球节点', exact: true })).toBeVisible();
  await expect(page.locator('.geo-summary')).toContainText('12');
  await expect(page.locator('.geo-unlocated')).toContainText('dev_oc_002');
  const unlocatedTrigger = page.locator('.geo-unlocated').getByRole('button', { name: 'dev_oc_002' });
  await unlocatedTrigger.click();
  const unlocatedDrawer = page.getByRole('dialog', { name: 'dev_oc_002详情' });
  await expect(unlocatedDrawer).toContainText('未定位');
  await expect(unlocatedDrawer).toBeFocused();
  await page.keyboard.press('Escape');
  await expect(unlocatedDrawer).toHaveCount(0);
  await expect(unlocatedTrigger).toBeFocused();
  await unlocatedTrigger.click();
  await page.getByRole('button', { name: '关闭详情' }).click();
  await expect(unlocatedTrigger).toBeFocused();
  await unlocatedTrigger.click();
  if ((page.viewportSize()?.width ?? 0) > 720) await page.locator('.geo-chart').click({ position: { x: 8, y: 8 } });
  else await page.keyboard.press('Escape');
  await expect(unlocatedDrawer).toHaveCount(0);
  await expect(page.getByRole('navigation', { name: '地理层级' })).toContainText('全球');
  await page.getByLabel('租户', { exact: true }).selectOption('ten_202609_001');
  await page.getByLabel('区域', { exact: true }).selectOption('AS');
  await page.getByRole('button', { name: '应用' }).click();
  await expect(page.locator('.geo-summary')).toContainText('1');
  await expect(page.locator('.geo-list')).toContainText('亚洲');
  await expect(page.locator('.geo-list')).not.toContainText('欧洲');
  await page.locator('.geo-list').getByRole('button', { name: '亚洲', exact: true }).click();
  await expect(page.locator('.geo-list')).toContainText('中国');
  await page.locator('.geo-list').getByRole('button', { name: '中国', exact: true }).click();
  await expect(page.locator('.geo-list')).toContainText('中国节点');
  const nodeTrigger = page.locator('.geo-list').getByRole('button', { name: '查看中国节点详情' });
  await nodeTrigger.click();
  const nodeDrawer = page.getByRole('dialog', { name: '中国节点详情' });
  await expect(nodeDrawer).toContainText('node_cn_001');
  await expect(nodeDrawer).toBeFocused();
  await page.getByRole('button', { name: '关闭详情' }).click();
  await expect(nodeTrigger).toBeFocused();
  await page.locator('.geo-list').getByRole('button', { name: '中国节点', exact: true }).click();
  await page.locator('.geo-list').getByRole('button', { name: 'dev_as_001', exact: true }).click();
  await expect(page.getByRole('dialog', { name: 'dev_as_001详情' })).toContainText('121.47, 31.23');
  await page.getByRole('button', { name: '关闭详情' }).click();
  await page.getByRole('navigation', { name: '地理层级' }).getByRole('button', { name: '全球' }).click();
  await expect(page.locator('.geo-list')).toContainText('亚洲');
  await page.getByLabel('区域', { exact: true }).selectOption('');
  await page.getByLabel('国家', { exact: true }).selectOption('ZA');
  await page.getByLabel('节点', { exact: true }).selectOption('node_za_001');
  await page.getByLabel('状态', { exact: true }).selectOption('offline');
  await page.getByRole('button', { name: '应用' }).click();
  await expect(page.locator('.geo-list')).toContainText('非洲');
  await expect(page.locator('.geo-summary')).toContainText('1');
  expect(errors).toEqual([]);
});

test('IOT-GEO-001 clears old tenant data and detail when identity is denied', async ({ page }) => {
  await page.goto('/geography');
  await expect(page.locator('.geo-summary')).toContainText('12');
  await page.locator('.geo-unlocated').getByRole('button', { name: 'dev_oc_002' }).click();
  await expect(page.getByRole('dialog', { name: 'dev_oc_002详情' })).toBeVisible();
  await page.getByLabel('演示身份').selectOption('viewer');
  await expect(page.getByRole('dialog', { name: 'dev_oc_002详情' })).toHaveCount(0);
  await expect(page.locator('.geo-summary')).toHaveCount(0);
  await expect(page.locator('.geo-unlocated')).toHaveCount(0);
  await expect(page.getByRole('alert')).toContainText('无权查看该租户数据');
  await expect(page.getByRole('button', { name: '重试' })).toHaveCount(0);
  await page.getByLabel('演示身份').selectOption('platformAdmin');
  await expect(page.locator('.geo-summary')).toContainText('12');
  await page.getByText('演示状态').click();
  await page.getByLabel('Mock 场景').selectOption('offline');
  await expect(page.getByRole('alert')).toContainText('非最新');
  await expect(page.getByRole('button', { name: '重试' })).toBeVisible();
  await expect(page.locator('.geo-summary')).toContainText('12');
  await page.getByLabel('Mock 场景').selectOption('forbidden');
  await expect(page.getByRole('alert')).toContainText('无权查看该租户数据');
  await expect(page.getByRole('button', { name: '重试' })).toHaveCount(0);
  await expect(page.locator('.geo-summary')).toHaveCount(0);
  await expect(page.getByRole('alert')).not.toContainText('非最新');
  await page.getByLabel('Mock 场景').selectOption('normal');
  await expect(page.locator('.geo-summary')).toContainText('12');
  await page.getByLabel('租户', { exact: true }).selectOption('ten_202609_001');
  await page.getByRole('button', { name: '应用' }).click();
  await expect(page.locator('.geo-summary')).toContainText('设备 6');
  await expect(page.locator('.geo-unlocated')).not.toContainText('dev_oc_002');
});

test('IOT-GEO-001 keeps the applied map when a custom UTC range is invalid', async ({ page }) => {
  await page.goto('/geography');
  await expect(page.locator('.geo-summary')).toContainText('12');
  await page.getByLabel('时间范围').selectOption('custom');
  await page.getByLabel('开始时间').fill('2026-09-16T08:00');
  await page.getByLabel('结束时间').fill('2026-09-17T08:00');
  await page.getByRole('button', { name: '应用' }).click();
  await expect(page.locator('.geo-summary')).toContainText('12');
  await page.getByLabel('结束时间').fill('2026-09-16T07:00');
  await page.getByRole('button', { name: '应用' }).click();
  await expect(page.locator('#geo-range-error')).toContainText('请选择有效的 30 天内 UTC 时间范围');
  await expect(page.getByLabel('结束时间')).toBeFocused();
  await expect(page.getByLabel('结束时间')).toHaveAttribute('aria-invalid', 'true');
  await expect(page.getByLabel('结束时间')).toHaveAttribute('aria-describedby', 'geo-range-error');
  await expect(page.locator('.geo-summary')).toContainText('12');
  await page.getByLabel('开始时间').fill('');
  await page.getByRole('button', { name: '应用' }).click();
  await expect(page.getByLabel('开始时间')).toBeFocused();
  await expect(page.getByLabel('开始时间')).toHaveAttribute('aria-invalid', 'true');
  await page.getByRole('button', { name: '重置' }).click();
  await expect(page.locator('#geo-range-error')).toHaveCount(0);
});

test('IOT-GEO-001 sorts and paginates a dense node list and opens device detail', async ({ page }) => {
  await page.goto('/tenants');
  await page.getByRole('button', { name: '华东智联' }).click();
  await page.getByRole('button', { name: '配额', exact: true }).click();
  await page.getByRole('button', { name: '编辑配额' }).click();
  await page.getByLabel('设备上限', { exact: true }).fill('20');
  await page.getByRole('button', { name: '预览影响' }).click();
  await page.getByRole('button', { name: '保存配额' }).click();
  await page.goto('/devices');
  await page.getByRole('button', { name: 'CSV 导入' }).click();
  const rows = Array.from({ length: 11 }, (_, index) => `分页设备${index + 1}号,AS,CN,演示`);
  await page.getByLabel('导入 CSV 文件').setInputFiles({ name: 'geo-devices.csv', mimeType: 'text/csv', buffer: Buffer.from(['name,region,countryCode,tags', ...rows].join('\n')) });
  await expect(page.getByRole('dialog', { name: 'CSV 导入设备' })).toContainText('预览：11 台未激活设备');
  await page.getByRole('button', { name: '确认导入' }).click();
  await page.evaluate(() => {
    const key = 'iot-atlas-devices-v1';
    const rows = JSON.parse(localStorage.getItem(key) || '[]') as { name: string; location: [number, number] | null }[];
    let placed = 0;
    for (const row of rows) if (row.name.startsWith('分页设备') && placed < 2) { row.location = [121.47, 31.23]; placed += 1; }
    localStorage.setItem(key, JSON.stringify(rows));
  });
  await page.goto('/geography');
  await page.getByLabel('节点', { exact: true }).selectOption('node_cn_001');
  await page.getByRole('button', { name: '应用' }).click();
  await page.locator('.geo-list').getByRole('button', { name: '亚洲', exact: true }).click();
  await page.locator('.geo-list').getByRole('button', { name: '中国', exact: true }).click();
  await page.locator('.geo-list').getByRole('button', { name: '中国节点', exact: true }).click();
  const list = page.locator('.geo-list');
  await expect(list.getByRole('navigation', { name: '节点列表分页' })).toContainText('共 12 项');
  await expect(page.locator('.geo-chart svg text').filter({ hasText: '3' })).toBeVisible();
  await expect(list.locator('tbody tr')).toHaveCount(10);
  await list.getByRole('button', { name: '下一页' }).click();
  await expect(list.locator('tbody tr')).toHaveCount(2);
  await list.getByRole('button', { name: '名称' }).click();
  await expect(list.locator('th').first()).toHaveAttribute('aria-sort', 'ascending');
  await expect(list.locator('tbody tr')).toHaveCount(10);
  await list.locator('tbody tr').first().locator('td').first().getByRole('button').click();
  const drawer = page.getByRole('dialog');
  await expect(drawer.getByRole('link', { name: '查看设备详情' })).toHaveAttribute('href', /\/devices\?device=/);
  await drawer.getByRole('link', { name: '查看设备详情' }).click();
  await expect(page).toHaveURL(/\/devices\?device=/);
  await expect(page.getByRole('button', { name: '关闭设备详情' })).toBeVisible();
});

test('IOT-GEO-001 map fallback, permissions, theme and narrow layout', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/geography');
  await expect(page.locator('.geo-chart svg')).toBeVisible();
  await page.getByRole('button', { name: '放大地图' }).click();
  await page.getByRole('button', { name: '缩小地图' }).click();
  await page.getByRole('button', { name: '定位到全球' }).click();
  await expect(page.locator('.geo-chart svg')).toBeVisible();
  await page.getByRole('button', { name: '列表视图' }).click();
  await expect(page.locator('.geo-chart')).toHaveCount(0);
  await page.getByRole('button', { name: '地图视图' }).click();
  await page.getByText('演示状态').click();
  await page.getByLabel('Mock 场景').selectOption('partialFailure');
  await expect(page.getByRole('alert')).toContainText('地图不可用');
  await expect(page.locator('.geo-list')).toContainText('亚洲');
  await page.getByLabel('Mock 场景').selectOption('offline');
  await expect(page.getByRole('alert')).toContainText('非最新');
  await page.getByLabel('Mock 场景').selectOption('normal');
  await page.getByLabel('演示身份').selectOption('viewer');
  await expect(page.getByRole('alert')).toContainText('无权查看该租户数据');
  await page.getByLabel('演示身份').selectOption('platformAdmin');
  await page.getByLabel('主题').selectOption('light');
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light');
  await expect(page.locator('.geo-list')).toContainText('亚洲');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect((await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()).violations.map(item => ({ id: item.id, targets: item.nodes.map(node => node.target) }))).toEqual([]);
  expect(errors).toEqual([]);
});

