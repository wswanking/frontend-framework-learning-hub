  await legend.getByRole('button', { name: '离线' }).click();
  await expect(legend.getByRole('button', { name: '离线' })).toHaveAttribute('aria-pressed', 'true');
  await expect(page.getByLabel('状态', { exact: true })).toHaveValue('offline');
  await expect(page.locator('.geo-summary')).toContainText('设备 1');
