test('IOT-FIRMWARE-001 shows actual local read progress before checksum completes', async ({ page }) => {
  await page.goto('/firmware');
  await page.getByRole('button', { name: '新建固件' }).click();
  await page.evaluate(() => { File.prototype.stream = function () { const bytesPromise = this.arrayBuffer(); return new ReadableStream<Uint8Array<ArrayBuffer>>({ async start(controller) { const bytes = new Uint8Array(await bytesPromise); controller.enqueue(bytes.slice(0, 1)); await new Promise(resolve => setTimeout(resolve, 500)); controller.enqueue(bytes.slice(1)); controller.close(); } }); }; });
  await page.getByLabel('本地固件文件').setInputFiles({ name: 'progress.bin', mimeType: 'application/octet-stream', buffer: Buffer.from('abc') });
  await expect(page.getByRole('progressbar', { name: '固件文件读取进度' })).toBeVisible();
  await expect(page.locator('.firmware-form [role="status"]')).toContainText('正在读取文件');
  await expect(page.locator('.firmware-form [role="status"]')).toContainText('校验完成');
  await expect(page.getByRole('progressbar', { name: '固件文件读取进度' })).toHaveCount(0);
});

