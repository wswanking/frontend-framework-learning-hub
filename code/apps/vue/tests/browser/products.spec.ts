test('IOT-PRODUCT-001 locates invalid model JSON and preserves the draft', async ({ page }) => {
  await page.goto('/products');
  await page.locator('.product-table-wrap').getByRole('button', { name: '工业温湿度传感器' }).click();
  await page.getByRole('tab', { name: '物模型' }).click();
  await page.locator('tr').filter({ hasText: 'temperature' }).getByRole('button', { name: '编辑' }).click();
  await page.locator('.model-mode').getByRole('button', { name: 'JSON' }).click();
  const input = page.getByLabel('物模型 JSON');
  const original = await input.inputValue();
  const invalid = original.replace('"kind": "property"', '"kind":,');
  expect(invalid).not.toBe(original);
  await input.fill(invalid);
  await page.locator('.model-mode').getByRole('button', { name: '表单' }).click();
  await expect(input).toBeVisible();
  await expect(input).toHaveValue(invalid);
  const errorLine = invalid.slice(0, invalid.indexOf('"kind":,')).split('\n').length;
  await expect(page.locator('.product-errors')).toContainText(`第 ${errorLine} 行`);
  expect(await input.evaluate(element => (element as HTMLTextAreaElement).selectionStart)).toBe(invalid.indexOf('"kind":,') + '"kind":'.length);
  await input.fill(original);
  await page.locator('.model-mode').getByRole('button', { name: '表单' }).click();
  await expect(page.getByLabel('模型标识符')).toHaveValue('temperature');
});

